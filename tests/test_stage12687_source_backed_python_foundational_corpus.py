def test_parser_span_row_is_exact_and_target_independent() -> None:
    module = load_module()
    data = (
        b"VALUE = 3\n\n"
        b"def compute(value: int) -> int:\n"
        b"    adjusted = value + VALUE\n"
        b"    assert adjusted >= value\n"
        b"    return adjusted\n"
    )
    tree = ast.parse(data.decode("utf-8"))
    snapshot = module.RepoSnapshot(
        local_path=Path("/unused"), repo_key="a" * 64,
        origin_url="https://example.com/source.git", revision="b" * 40,
        license_path="LICENSE", license_oid="c" * 40, license_id="MIT",
        python_blobs=[], license_sha256="f" * 64, component_key="d" * 64, split="train",
    )
    blob = module.Blob(oid="e" * 40, size=len(data), path="src/module.py")
    spans = module.candidate_spans(data, tree, snapshot.repo_key, blob.path)
    assert spans
    built = module.build_row(snapshot, blob, data, tree, spans[0])
    assert built is not None
    row, proof = built
    assert row["input_text"].count(module.MASK) == 1
    assert row["target"]["decoder_text"]
    assert proof["byte_exact_reinsertion_verified"] is True
    assert proof["ast_roundtrip_verified"] is True

    sys.path.insert(0, str(ROOT / "legacy_src"))
    from agentkernel_lite.training_data import ByteTokenizer, _row_text

    mutated = json.loads(json.dumps(row))
    mutated["target"]["decoder_text"] = "different verified target"
    tokenizer = ByteTokenizer()
    assert tokenizer.encode(_row_text(row), max_length=2048) == tokenizer.encode(_row_text(mutated), max_length=2048)

    repeated = b"def first():\n    return None\n\ndef second():\n    return None\n"
    repeated_tree = ast.parse(repeated.decode())
    return_node = next(node for node in ast.walk(repeated_tree) if isinstance(node, ast.Return))
    repeated_lines = repeated.splitlines(keepends=True)
    repeated_span = (
        module.byte_position(repeated_lines, return_node.lineno, return_node.col_offset),
        module.byte_position(repeated_lines, return_node.end_lineno, return_node.end_col_offset),
        "Return",
    )
    repeated_blob = module.Blob(oid="9" * 40, size=len(repeated), path="repeated.py")
    assert module.build_row(snapshot, repeated_blob, repeated, repeated_tree, repeated_span) is None

    normalized = b"def first():\n    return None\n\ndef second():\n    # returnNone\n    return 1\n"
    normalized_tree = ast.parse(normalized.decode())
    normalized_node = next(node for node in ast.walk(normalized_tree) if isinstance(node, ast.Return))
    normalized_lines = normalized.splitlines(keepends=True)
    normalized_span = (
        module.byte_position(normalized_lines, normalized_node.lineno, normalized_node.col_offset),
        module.byte_position(normalized_lines, normalized_node.end_lineno, normalized_node.end_col_offset),
        "Return",
    )
    normalized_blob = module.Blob(oid="8" * 40, size=len(normalized), path="normalized.py")
    assert module.build_row(snapshot, normalized_blob, normalized, normalized_tree, normalized_span) is None


def test_cat_blobs_fails_closed_on_corruption_and_reaps_timeout(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    module = load_module()
    blob = module.Blob(oid="0" * 40, size=3, path="source.py")

    class ForgedProcess:
        returncode = 0

        def communicate(self, _input: bytes, timeout: int) -> tuple[bytes, bytes]:
            return f"{blob.oid} blob 3\n".encode("ascii") + b"bad\n", b""

    monkeypatch.setattr(module.subprocess, "Popen", lambda *args, **kwargs: ForgedProcess())
    with pytest.raises(module.Stage12687Error, match="git_blob_identity_mismatch"):
        module.cat_blobs(tmp_path, [blob])

    class TimedOutProcess:
        returncode = -9

        def __init__(self) -> None:
            self.killed = False
            self.calls = 0

        def communicate(self, _input: bytes | None = None, timeout: int | None = None) -> tuple[bytes, bytes]:
            self.calls += 1
            if self.calls == 1:
                raise module.subprocess.TimeoutExpired(["git"], timeout)
            return b"", b""

        def kill(self) -> None:
            self.killed = True

    timed_out = TimedOutProcess()
    monkeypatch.setattr(module.subprocess, "Popen", lambda *args, **kwargs: timed_out)
    with pytest.raises(module.Stage12687Error, match="git_cat_file_timeout"):
        module.cat_blobs(tmp_path, [blob])
    assert timed_out.killed is True
    assert timed_out.calls == 2


def test_secure_atomic_write_rejects_temporary_symlink(tmp_path: Path) -> None:
    module = load_module()
    target = tmp_path / "artifact.json"
    data = b"protected output\n"
    temporary = tmp_path / f".{target.name}.tmp.{os.getpid()}.{module.sha256_bytes(data)[:12]}"
    victim = tmp_path / "victim.txt"
    victim.write_text("unchanged", encoding="utf-8")
    temporary.symlink_to(victim)
    with pytest.raises(FileExistsError):
        module.secure_atomic_write(target, data, mode=0o600)
    assert victim.read_text(encoding="utf-8") == "unchanged"

    real_parent = tmp_path / "real-parent"
    real_parent.mkdir()
    linked_parent = tmp_path / "linked-parent"
    linked_parent.symlink_to(real_parent, target_is_directory=True)
    with pytest.raises(OSError):
        module.open_directory_nofollow(linked_parent)

    source = tmp_path / "source"
    destination = tmp_path / "destination"
    source.mkdir()
    destination.mkdir()
    parent_fd = module.open_directory_nofollow(tmp_path)
    try:
        with pytest.raises(module.Stage12687Error, match="immutable_generation_exists"):
            module.rename_noreplace(parent_fd, source.name, destination.name)
    finally:
        os.close(parent_fd)
    assert source.is_dir()
    assert destination.is_dir()


