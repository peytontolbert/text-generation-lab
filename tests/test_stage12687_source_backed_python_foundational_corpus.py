def load_module():
    spec = importlib.util.spec_from_file_location("stage12687", SCRIPT)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def git(repo: Path, *args: str, env: dict[str, str] | None = None) -> str:
    result = subprocess.run(
        ["git", "-C", str(repo), *args], check=True, text=True,
        stdout=subprocess.PIPE, stderr=subprocess.PIPE, env=env,
    )
    return result.stdout.strip()


def create_repo(source_root: Path, index: int) -> tuple[Path, str, str]:
    repo = source_root / f"repo-{index:03d}"
    repo.mkdir()
    git(repo, "init", "-q")
    git(repo, "config", "user.email", "fixture@example.invalid")
    git(repo, "config", "user.name", "Fixture")
    origin = f"https://example.com/repo-{index:03d}.git"
    git(repo, "remote", "add", "origin", origin)
    (repo / "LICENSE").write_text(
        "MIT License\n\nPermission is hereby granted, free of charge, to any person obtaining a copy.\n"
        "THE SOFTWARE IS PROVIDED AS IS.\n",
        encoding="utf-8",
    )
    for file_index in range(3):
        (repo / f"module_{file_index}.py").write_text(
            f"\nVALUE_{index}_{file_index} = {index + file_index}\n\n"
            f"def compute_{index}_{file_index}(value: int) -> int:\n"
            f"    adjusted = value + VALUE_{index}_{file_index}\n"
            "    assert adjusted >= value\n"
            "    return adjusted\n\n"
            f"class Holder_{index}_{file_index}:\n"
            "    enabled = True\n\n"
            f"def validate_{index}_{file_index}(candidate: int) -> bool:\n"
            "    normalized = max(candidate, 0)\n"
            "    return normalized == candidate\n",
            encoding="utf-8",
        )
    git(repo, "add", "LICENSE", "module_0.py", "module_1.py", "module_2.py")
    env = dict(os.environ)
    env.update({
        "GIT_AUTHOR_DATE": f"2020-01-{index % 28 + 1:02d}T00:00:00Z",
        "GIT_COMMITTER_DATE": f"2020-01-{index % 28 + 1:02d}T00:00:00Z",
    })
    git(repo, "commit", "-q", "-m", "fixture", env=env)
    return repo, origin, git(repo, "rev-parse", "HEAD")


