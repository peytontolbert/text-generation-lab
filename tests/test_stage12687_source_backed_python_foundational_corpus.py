def test_publication_rejects_pending_directory_replacement(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    module = load_module()
    output = tmp_path / "artifact"
    generation_id = "c" * 24
    original_write = module.write_file_at
    writes = 0

    def replace_after_summary(directory_fd, name, data, *, mode):
        nonlocal writes
        identity = original_write(directory_fd, name, data, mode=mode)
        writes += 1
        if name == "summary.json":
            private = output / "private"
            pending = private / f".pending-{generation_id}-{os.getpid()}"
            displaced = private / ".displaced-pinned-pending"
            os.rename(pending, displaced)
            pending.mkdir()
        return identity

    monkeypatch.setattr(module, "write_file_at", replace_after_summary)
    with pytest.raises(module.Stage12687Error, match="pending_generation_inode_mismatch"):
        module.publish_generation(
            output, generation_id, {"artifact.jsonl": b"safe\n"}, {"safe": True}
        )
    assert writes == 2
    assert not (output / "private" / generation_id).exists()
    assert (output / "private" / ".displaced-pinned-pending" / "artifact.jsonl").is_file()


def test_publication_fsync_and_mode_order_is_durable(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    module = load_module()
    events: list[tuple[str, int, int | None]] = []
    original_fchmod = module.os.fchmod
    original_fsync = module.os.fsync
    original_rename = module.rename_noreplace

    def recording_fchmod(fd: int, mode: int) -> None:
        events.append(("fchmod", fd, mode))
        original_fchmod(fd, mode)

    def recording_fsync(fd: int) -> None:
        events.append(("fsync", fd, None))
        original_fsync(fd)

    def recording_rename(parent_fd: int, source: str, destination: str) -> None:
        events.append(("rename", parent_fd, None))
        original_rename(parent_fd, source, destination)

    monkeypatch.setattr(module.os, "fchmod", recording_fchmod)
    monkeypatch.setattr(module.os, "fsync", recording_fsync)
    monkeypatch.setattr(module, "rename_noreplace", recording_rename)
    output = tmp_path / "artifact"
    generation = module.publish_generation(
        output, "d" * 24, {"artifact.jsonl": b"safe\n"}, {"safe": True}
    )
    rename_index = next(index for index, event in enumerate(events) if event[0] == "rename")
    file_mode_events = [
        (index, event) for index, event in enumerate(events)
        if event[0] == "fchmod" and event[2] == 0o400
    ]
    assert len(file_mode_events) == 2
    for mode_index, (_, fd, _) in file_mode_events:
        assert any(
            event[0] == "fsync" and event[1] == fd
            for event in events[mode_index + 1:rename_index]
        )
    pending_mode_index, pending_mode = next(
        (index, event) for index, event in enumerate(events)
        if event[0] == "fchmod" and event[2] == 0o500
    )
    assert pending_mode_index < rename_index
    assert any(
        event[0] == "fsync" and event[1] == pending_mode[1]
        for event in events[pending_mode_index + 1:rename_index]
    )
    rename_parent_fd = events[rename_index][1]
    assert any(
        event[0] == "fsync" and event[1] == rename_parent_fd
        for event in events[rename_index + 1:]
    )
    assert generation.stat().st_mode & 0o777 == 0o500
    assert (generation / "artifact.jsonl").stat().st_mode & 0o777 == 0o400
    assert (generation / "summary.json").stat().st_mode & 0o777 == 0o400


